#!/usr/bin/env python3
"""Generates Scala versions of the contraband-generated classes and enums of
Zinc's compiler-interface `xsbti.api` (Java), for the Scala Native build of the
Scala 3 compiler (native/sbt-interfaces).

    generate.py <compiler-interface sources> <output dir> <version>

for example, with compiler-interface-1.12.1-sources.jar unpacked in /tmp/ci:

    generate.py /tmp/ci src/xsbti/api 1.12.1

Modifiers, Lazy, AbstractLazy, SafeLazy (hand-written in Zinc) and the enums
UseScope and DependencyContext are ported by hand.

The Java classes follow contraband's template exactly: static `create`/`of`
factories, private fields, a protected constructor, getters (forcing `Lazy`
fields), `withX` copies, and structural `equals`/`hashCode`/`toString` (or
identity ones for classes with lazy members). The Scala versions keep every
public member with the same erased signature, so that their NIR names are the
ones the compiler, compiled against the Java classes, refers to.
"""
import pathlib
import re
import sys

src = pathlib.Path(sys.argv[1]) / "xsbti" / "api"
out = pathlib.Path(sys.argv[2])
version = sys.argv[3]

# Zinc's analysis types (not used by the compiler), and the files ported by
# hand or already present.
SKIP = {
    "AnalyzedClass", "Companions", "NameHash", "ExternalDependency",
    "InternalDependency", "DependencyContext", "Modifiers", "SafeLazy",
    "AbstractLazy", "Lazy",
}

PRIMITIVES = {"boolean": "Boolean", "int": "Int", "long": "Long", "byte": "Byte"}


def scala_type(t: str) -> str:
    t = t.strip()
    if t.endswith("[]"):
        return f"Array[{scala_type(t[:-2])}]"
    m = re.fullmatch(r"(?:xsbti\.api\.)?Lazy<(.+)>", t)
    if m:
        return f"Lazy[{scala_type(m.group(1))}]"
    if t in PRIMITIVES:
        return PRIMITIVES[t]
    if t.startswith("xsbti.api."):
        return t[len("xsbti.api."):]
    return t


def params(text: str):
    """`T1 _a, T2 _b` as [(java type, name without underscore)]."""
    result = []
    depth = 0
    current = ""
    for ch in text:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            result.append(current)
            current = ""
        else:
            current += ch
    if current.strip():
        result.append(current)
    out = []
    for p in result:
        t, n = p.strip().rsplit(" ", 1)
        out.append((t, n.lstrip("_")))
    return out


def wrap(prefix: str, items, suffix: str, indent: str = "    ", width: int = 100) -> str:
    """`prefix` + items joined by ", " + `suffix`, wrapped at `width`."""
    one = prefix + ", ".join(items) + suffix
    if len(one) <= width:
        return one
    lines, line = [], prefix
    for i, item in enumerate(items):
        piece = item + ("," if i < len(items) - 1 else suffix)
        if len(line) + len(piece) + 1 > width and line.strip():
            lines.append(line.rstrip())
            line = indent
        line += piece + " "
    lines.append(line.rstrip())
    return "\n".join(lines)


def header(name: str) -> str:
    return f"""/*
 * Scala version of xsbti/api/{name}.java from Zinc's compiler-interface
 * {version} (https://github.com/sbt/zinc), for the Scala Native build of the
 * compiler, generated by native/sbt-interfaces/generate.py.
 *
 * Zinc - The incremental compiler for Scala.
 * Copyright Scala Center, Lightbend, and Mark Harrah
 *
 * Licensed under Apache License 2.0
 * SPDX-License-Identifier: Apache-2.0
 */

package xsbti.api
"""


def gen_enum(name: str, text: str) -> str:
    body = re.search(r"public enum \w+ \{(.*?);", text, re.S).group(1)
    cases = [c.strip() for c in body.split(",") if c.strip()]
    return header(name) + (
        f"\nenum {name} extends java.lang.Enum[{name}]:\n"
        f"  case {', '.join(cases)}\n"
    )


def gen_class(name: str, text: str) -> str:
    m = re.search(
        r"public (final|abstract) class (\w+)(?: extends ([\w.]+))? implements java\.io\.Serializable \{",
        text,
    )
    kind, cls, parent = m.group(1), m.group(2), m.group(3)
    assert cls == name
    parent = parent[len("xsbti.api."):] if parent else None

    ctor = re.search(
        rf"protected {name}\((.*?)\) \{{\s*super\((.*?)\);", text, re.S
    )
    all_params = params(ctor.group(1))
    super_args = [a.strip().lstrip("_") for a in ctor.group(2).split(",") if a.strip()]
    own_fields = re.findall(r"^\s*private (.+?) (\w+);$", text, re.M)
    own = {n for _, n in own_fields}

    getters = re.findall(
        r"public (.+?) (\w+)\(\) \{\s*return this\.(\w+)(\.get\(\))?;", text
    )
    factories = re.findall(rf"public static {name} (create|of)\(", text)
    withs = re.findall(
        rf"public {name} (with\w+)\((.+?) (\w+)\) \{{\s*return new {name}\((.*?)\);",
        text,
    )
    identity = "object identity" in text

    lines = [header(name)]
    mods = "final " if kind == "final" else "abstract "
    ext = (
        f"extends {parent}({', '.join('_' + a for a in super_args)})\n    with java.io.Serializable"
        if parent
        else "extends java.io.Serializable"
    )
    ctor_params = [f"_{n}: {scala_type(t)}" for t, n in all_params]
    lines.append(wrap(f"{mods}class {name} protected[api] (", ctor_params, ")"))
    lines.append(f"    {ext}:")

    body = []
    for ret, getter, field, lazy in getters:
        assert field in own, (name, field)
        value = f"_{field}.get()" if lazy else f"_{field}"
        body.append(f"  def {getter}(): {scala_type(ret)} = {value}")
    for method, ptype, pname, wargs in withs:
        converted = []
        for a in [x.strip() for x in wargs.split(",") if x.strip()]:
            if a.endswith("()") or a == pname:
                converted.append(a)
            else:
                assert a in own, (name, a)
                converted.append("_" + a)
        body.append(
            f"  def {method}({pname}: {scala_type(ptype)}): {name} =\n"
            + wrap(f"    new {name}(", converted, ")", "      ")
        )

    # equals, hashCode and toString, as contraband writes them
    if identity:
        body.append(
            "  // Lazy members: object identity, which avoids circularity\n"
            "  override def equals(obj: Any): Boolean = this eq obj.asInstanceOf[AnyRef]\n"
            "  override def hashCode(): Int = super.hashCode()\n"
            "  override def toString(): String = super.toString()"
        )
    else:
        def eq(t, n):
            st = scala_type(t)
            if st.startswith("Array["):
                return (f"java.util.Arrays.deepEquals({n}().asInstanceOf[Array[AnyRef]],\n          "
                        f"o.{n}().asInstanceOf[Array[AnyRef]])")
            if t in PRIMITIVES:
                return f"{n}() == o.{n}()"
            return f"{n}().equals(o.{n}())"

        def hash(t, n):
            st = scala_type(t)
            if st.startswith("Array["):
                return f"java.util.Arrays.deepHashCode({n}().asInstanceOf[Array[AnyRef]])"
            if t in PRIMITIVES:
                boxed = {"boolean": "Boolean", "int": "Integer", "long": "Long", "byte": "Byte"}[t]
                return f"java.lang.{boxed}.hashCode({n}())"
            return f"{n}().hashCode()"

        comparisons = [eq(t, n) for t, n in all_params]
        if comparisons:
            joined = " &&\n        ".join(comparisons)
            matched = f"\n      (this eq o) || (\n        {joined})"
        else:
            matched = " true"
        body.append(
            "  override def equals(obj: Any): Boolean = obj match\n"
            f"    case o: {name} =>{matched}\n"
            "    case _ => false"
        )
        acc = f'17 + "xsbti.api.{name}".hashCode()'
        for t, n in all_params:
            acc = f"37 * ({acc}) +\n      {hash(t, n)}"
        body.append(f"  override def hashCode(): Int =\n    37 * ({acc})")
        # "X(" + "a: " + a() + ", " + "b: " + b() + ")", wrapped at 100
        fields = [f'"{n}: " + {n}()' for _, n in all_params]
        items = [f'"{name}("'] + [f + ' + ", "' for f in fields[:-1]] + fields[-1:] + ['")"']
        line, wrapped = "    ", []
        for i, item in enumerate(items):
            piece = item + (" +" if i < len(items) - 1 else "")
            if len(line) + len(piece) > 100 and line.strip():
                wrapped.append(line.rstrip())
                line = "      "
            line += piece + " "
        wrapped.append(line.rstrip())
        body.append("  override def toString(): String =\n" + "\n".join(wrapped))

    lines.append("\n\n".join(body) if body else "")
    if factories:
        lines.append(f"\nobject {name}:")
        plain = [f"{n}: {scala_type(t)}" for t, n in all_params]
        for f in factories:
            lines.append(wrap(f"  def {f}(", plain, f"): {name} =", "      "))
            lines.append(wrap(f"    new {name}(", [n for _, n in all_params], ")", "      "))
    return "\n".join(lines).rstrip() + "\n"


out.mkdir(parents=True, exist_ok=True)
count = 0
for java in sorted(src.glob("*.java")):
    name = java.stem
    if name in SKIP:
        continue
    text = java.read_text()
    assert "contraband" in text, name
    code = gen_enum(name, text) if re.search(r"public enum ", text) else gen_class(name, text)
    (out / f"{name}.scala").write_text(code)
    count += 1
print(f"{count} files")
